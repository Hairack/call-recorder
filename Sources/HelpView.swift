                    card("Как это работает",
                         "Приложение записывает звук через микрофон телефона. Когда разговор идёт по громкой связи, микрофон слышит и вас, и собеседника — записывается весь разговор.")

                    card("Почему нельзя иначе",
                         "Система iOS не даёт ни одному стороннему приложению доступ к звуку самого телефонного звонка. Ни из App Store, ни после установки вручную (Sideloadly). Это ограничение Apple, обойти его на iPhone XR (iOS 18) нельзя.")

                    card("Как записать разговор — по шагам",
