                         "При установке вручную через Sideloadly бесплатным Apple ID приложение работает 7 дней. Потом подключите телефон к компьютеру и установите заново — данные и записи сохранятся.")

                    card("Альтернатива без ограничений",
                         "Если нужно записывать много и надолго: используйте сервис записи у вашего оператора связи или VoIP-приложения (например, звонки через мессенджеры можно записывать их средствами).")
