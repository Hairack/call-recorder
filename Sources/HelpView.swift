                    card("Что делать, если телефон в руке",
                         "Можно надиктовать суть разговора после его окончания — создайте запись и проговорите главное. Либо используйте гарнитуру с собственным диктофоном.")

                    card("Законодательство (Россия)",
                         "Записывать свой собственный разговор для личных целей можно. Публиковать запись разговора с другим человеком без его согласия — нельзя. Для деловых переговоров лучше предупредить собеседника, что ведёте запись.")

                    card("Где лежат файлы",
